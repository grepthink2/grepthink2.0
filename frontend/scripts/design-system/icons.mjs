/**
 * The lucide icons the design-system `Icon` carries: exactly those the app imports from
 * `lucide-react` anywhere under src/ (tests and the kit's previews left out: a preview bundles its
 * own icons, and an icon only a preview shows is not one the app uses), found again on every
 * build, so an icon the app starts to use reaches the system with no list to edit.
 *
 * Imports are read by pattern over the source with comments and strings blanked (names.mjs reads
 * declarations the same way): `import { A, B as C } from 'lucide-react'` gives A and B, and a
 * type-only import, or a `type` specifier, gives nothing.
 */

import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { splitCodeAndComments } from '../ownership.mjs';

// `import {…} from 'lucide-react'`, read with the module name still in place: comments are
// blanked first, string contents only after the match.
const LUCIDE_IMPORT = /^import[ \t]+(type[ \t]+)?\{([^}]*)\}[ \t]*from[ \t]*(['"])lucide-react\3/gm;

function withoutComments(source) {
  return splitCodeAndComments(source, { script: true }).code;
}

function sourceFiles(dir) {
  const files = [];
  for (const entry of readdirSync(dir).sort()) {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) {
      if (entry !== '__tests__') files.push(...sourceFiles(path));
    } else if (/\.tsx?$/.test(entry) && !entry.endsWith('.d.ts') && !entry.includes('.test.') && !entry.endsWith('.preview.tsx')) {
      files.push(path);
    }
  }
  return files;
}

/**
 * @param {string} srcDir
 * @returns {string[]} the icon names, sorted, each once
 */
export function collectLucideIcons(srcDir) {
  const names = new Set();
  for (const path of sourceFiles(srcDir)) {
    const source = readFileSync(path, 'utf8');
    if (!source.includes('lucide-react')) continue;
    for (const [, typeOnly, specifiers] of withoutComments(source).matchAll(LUCIDE_IMPORT)) {
      if (typeOnly) continue;
      for (const part of specifiers.split(',')) {
        const imported = part.trim().split(/\s+as\s+/)[0];
        if (imported && !imported.startsWith('type ')) names.add(imported);
      }
    }
  }
  return [...names].sort();
}

/**
 * Writes the module `Icon` reads: `ICONS`, each icon under the name the app imports it by.
 * @param {string[]} names
 * @param {string} outFile
 */
export function writeIconMap(names, outFile) {
  const list = names.join(', ');
  const text = [
    '// Generated by scripts/design-system/icons.mjs for `npm run design:build`. Do not edit.',
    `import { ${list} } from 'lucide-react';`,
    "import type { LucideIcon } from 'lucide-react';",
    '',
    `export const ICONS: Record<string, LucideIcon> = { ${list} };`,
    '',
  ].join('\n');
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, text);
}
